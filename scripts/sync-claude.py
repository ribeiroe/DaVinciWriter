"""Generate Claude Code wrappers (.claude/commands + .claude/agents) from the
.github source files, so the single source of truth stays in .github/ while
Claude Code users get native slash commands and Task-invocable subagents.

Usage:
    python scripts/sync-claude.py            # (re)generate .claude/ wrappers
    python scripts/sync-claude.py --check    # exit 1 if wrappers are stale (CI)
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROMPTS_DIR = ROOT / ".github" / "prompts"
AGENTS_DIR = ROOT / ".github" / "agents"
COMMANDS_OUT = ROOT / ".claude" / "commands"
AGENTS_OUT = ROOT / ".claude" / "agents"

# Abstract tool names used in .github agent frontmatter -> Claude Code tool IDs
TOOL_MAP = {
    "read": ["Read"],
    "search": ["Grep", "Glob"],
    "edit": ["Edit", "Write"],
    "agent": ["Task"],
    "todo": ["TodoWrite"],
}

GENERATED_NOTE = (
    "<!-- GENERATED by scripts/sync-claude.py — do not edit. "
    "Edit the .github source file and re-run the script. -->"
)


def _frontmatter(text: str) -> dict:
    """Parse the simple key: value frontmatter used by the .github files."""
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n", text, re.DOTALL)
    fm = {}
    if not m:
        return fm
    for line in m.group(1).splitlines():
        kv = re.match(r"^([A-Za-z_-]+):\s*(.*)$", line)
        if kv:
            fm[kv.group(1).strip()] = kv.group(2).strip().strip("'\"")
    return fm


def _yaml_quote(value: str) -> str:
    return '"' + value.replace('"', '\\"') + '"'


def _claude_tools(raw_tools: str) -> str:
    names = re.findall(r"[a-zA-Z_-]+", raw_tools or "")
    out: list[str] = []
    for n in names:
        for t in TOOL_MAP.get(n.lower(), []):
            if t not in out:
                out.append(t)
    return ", ".join(out) if out else "Read, Grep, Glob"


def build_files() -> dict[Path, str]:
    """Return {output_path: content} for every wrapper."""
    files: dict[Path, str] = {}

    for prompt in sorted(PROMPTS_DIR.glob("*.prompt.md")):
        name = prompt.name.removesuffix(".prompt.md")
        desc = _frontmatter(prompt.read_text(encoding="utf-8")).get(
            "description", f"Run the DaVinci {name} workflow"
        )
        rel = f".github/prompts/{prompt.name}"
        files[COMMANDS_OUT / f"{name}.md"] = (
            f"---\n"
            f"description: {_yaml_quote(desc)}\n"
            f"---\n"
            f"{GENERATED_NOTE}\n\n"
            f"Read `{rel}` now and execute its workflow end to end as this "
            f"session's task. That file is the single source of truth for this "
            f"command — follow it exactly, including its constraints and output "
            f"conventions. Input provided with the command: $ARGUMENTS\n"
        )

    for agent in sorted(AGENTS_DIR.glob("*.agent.md")):
        name = agent.name.removesuffix(".agent.md")
        fm = _frontmatter(agent.read_text(encoding="utf-8"))
        desc = fm.get("description", f"DaVinci {name} agent")
        tools = _claude_tools(fm.get("tools", ""))
        rel = f".github/agents/{agent.name}"
        files[AGENTS_OUT / f"{name}.md"] = (
            f"---\n"
            f"name: {name}\n"
            f"description: {_yaml_quote(desc)}\n"
            f"tools: {tools}\n"
            f"---\n"
            f"{GENERATED_NOTE}\n\n"
            f"Read `{rel}` (relative to the project root) and follow it exactly "
            f"as your operating instructions for this task. That file is the "
            f"single source of truth for this agent's behavior.\n"
        )

    return files


def main() -> int:
    check = "--check" in sys.argv
    files = build_files()

    stale = []
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")

    # Remove orphaned wrappers whose source file was deleted
    expected = set(files)
    for out_dir in (COMMANDS_OUT, AGENTS_OUT):
        if out_dir.exists():
            for f in out_dir.glob("*.md"):
                if f not in expected and GENERATED_NOTE in f.read_text(encoding="utf-8"):
                    stale.append(f)
                    if not check:
                        f.unlink()

    if check:
        if stale:
            print("STALE .claude/ wrappers (run: python scripts/sync-claude.py):")
            for p in stale:
                print(f"  {p.relative_to(ROOT)}")
            return 1
        print(f".claude/ wrappers in sync ({len(files)} files).")
        return 0

    print(f"Wrote {len(files)} wrappers ({len(stale)} changed).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
